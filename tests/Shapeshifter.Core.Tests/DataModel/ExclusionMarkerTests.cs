using System.Text;
using Shapeshifter.Core.Clipboard;

namespace Shapeshifter.Core.Tests.DataModel;

/// <summary>Password managers mark clipboard data that clipboard managers must not record.</summary>
public sealed class ExclusionMarkerTests
{
    private static Task<bool> IsExcluded(string[] formats, Dictionary<string, byte[]>? values = null) =>
        ClipboardFormatClassifier.IsExcludedFromHistoryAsync(
            formats,
            name => Task.FromResult(values is not null && values.TryGetValue(name, out var value) ? value : null));

    [Theory]
    [InlineData("ExcludeClipboardContentFromMonitorProcessing")]
    [InlineData("Clipboard Viewer Ignore")]
    [InlineData("org.nspasteboard.ConcealedType")]
    [InlineData("org.nspasteboard.TransientType")]
    [InlineData("org.nspasteboard.AutoGeneratedType")]
    public async Task PresenceMarkers_Exclude(string marker) =>
        Assert.True(await IsExcluded(["Text", marker]));

    [Fact]
    public async Task OrdinaryFormats_AreNotExcluded() =>
        Assert.False(await IsExcluded(["Text", "text/html", "UTF8_STRING", "image/png"]));

    [Theory]
    [InlineData(0, true)]
    [InlineData(1, false)]
    public async Task WindowsCanIncludeInClipboardHistory_ExcludesOnlyWhenZero(int value, bool expected)
    {
        var values = new Dictionary<string, byte[]> { ["CanIncludeInClipboardHistory"] = BitConverter.GetBytes(value) };
        Assert.Equal(expected, await IsExcluded(["Text", "CanIncludeInClipboardHistory"], values));
    }

    [Theory]
    [InlineData("secret", true)]
    [InlineData("secret\n", true)]
    [InlineData("public", false)]
    public async Task KdePasswordManagerHint_ExcludesSecrets(string hint, bool expected)
    {
        var values = new Dictionary<string, byte[]> { ["x-kde-passwordManagerHint"] = Encoding.UTF8.GetBytes(hint) };
        Assert.Equal(expected, await IsExcluded(["UTF8_STRING", "x-kde-passwordManagerHint"], values));
    }

    [Fact]
    public void MarkerFormats_AreNeverCapturedAsRawData()
    {
        Assert.False(ClipboardFormatClassifier.ShouldCapture("org.nspasteboard.ConcealedType"));
        Assert.False(ClipboardFormatClassifier.ShouldCapture("ExcludeClipboardContentFromMonitorProcessing"));
    }
}
