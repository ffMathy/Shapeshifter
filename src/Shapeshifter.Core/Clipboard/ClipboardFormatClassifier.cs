namespace Shapeshifter.Core.Clipboard;

/// <summary>
/// Knows the names that Windows, macOS and X11/Wayland use for the same kinds of clipboard data,
/// so that history items can be interpreted and restored without platform-specific code.
/// </summary>
public static class ClipboardFormatClassifier
{
    private static readonly HashSet<string> PlainTextFormats = new(StringComparer.OrdinalIgnoreCase)
    {
        // X11 / Wayland
        "UTF8_STRING", "STRING", "TEXT", "COMPOUND_TEXT", "UTF16_STRING", "text/plain", "text/plain;charset=utf-8",
        "text/plain;charset=UTF-8", "text/plain;charset=utf-16",
        // Windows
        "CF_TEXT", "CF_UNICODETEXT", "CF_OEMTEXT", "Text", "UnicodeText", "OEMText",
        // macOS
        "public.utf8-plain-text", "public.utf16-plain-text", "public.utf16-external-plain-text", "public.plain-text",
        "NSStringPboardType",
    };

    private static readonly HashSet<string> RichTextFormats = new(StringComparer.OrdinalIgnoreCase)
    {
        "text/html", "text/html;charset=utf-8", "HTML Format", "public.html", "Apple HTML pasteboard type",
        "text/rtf", "text/richtext", "application/rtf", "Rich Text Format", "public.rtf", "NeXT Rich Text Format v1.0 pasteboard type",
        "com.apple.flat-rtfd", "public.rtfd",
    };

    private static readonly HashSet<string> FileListFormats = new(StringComparer.OrdinalIgnoreCase)
    {
        "text/uri-list", "CF_HDROP", "FileDrop", "FileName", "FileNameW", "public.file-url", "NSFilenamesPboardType",
        "NSURLPboardType",
    };

    private static readonly HashSet<string> ImageFormats = new(StringComparer.OrdinalIgnoreCase)
    {
        "PNG", "CF_DIB", "CF_DIBV5", "CF_BITMAP", "Bitmap", "DeviceIndependentBitmap", "Format17", "JFIF", "GIF",
        "public.png", "public.tiff", "public.jpeg", "NeXT TIFF v4.0 pasteboard type", "Apple PNG pasteboard type",
    };

    /// <summary>
    /// Formats that must never be captured: protocol meta targets, OS handles that are not plain memory
    /// (reading them crashes or yields garbage) and in-process object references.
    /// </summary>
    private static readonly HashSet<string> IgnoredFormats = new(StringComparer.OrdinalIgnoreCase)
    {
        // X11 selection protocol targets
        "TARGETS", "MULTIPLE", "TIMESTAMP", "SAVE_TARGETS", "DELETE", "INCR", "_VERSION", "CLIPBOARD_MANAGER",
        // Windows handle-based and OLE formats
        "DataObject", "Ole Private Data", "Object Descriptor", "Link Source Descriptor", "Embed Source", "Link Source",
        "CF_ENHMETAFILE", "CF_METAFILEPICT", "EnhancedMetafile", "MetaFilePict", "CF_PALETTE", "Palette",
        "CF_OWNERDISPLAY", "CF_DSPBITMAP", "CF_DSPENHMETAFILE", "CF_DSPMETAFILEPICT", "CF_BITMAP",
        // macOS
        "com.apple.pasteboard.promised-file-url", "dyn.ah62d4rv4gu8yc6durvwwa3xmrvw1gkdusm1044pxqyuha2pxsvw0e55bsmwca7d3sbwu",
    };

    /// <summary>
    /// Formats whose mere presence means the copying application (typically a password manager) asked clipboard
    /// managers not to record the data.
    /// </summary>
    private static readonly HashSet<string> ExclusionMarkers = new(StringComparer.OrdinalIgnoreCase)
    {
        // Windows: https://learn.microsoft.com/windows/win32/dataxchg/clipboard-formats#cloud-clipboard-and-clipboard-history-formats
        "ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore",
        // macOS: http://nspasteboard.org
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    };

    /// <summary>Formats whose value decides whether the data may be recorded.</summary>
    public const string WindowsCanIncludeInHistoryFormat = "CanIncludeInClipboardHistory";

    public const string KdePasswordManagerHintFormat = "x-kde-passwordManagerHint";

    /// <summary>
    /// Whether the clipboard holds data the source application marked as sensitive or transient.
    /// <paramref name="readValue"/> reads a marker format's bytes for the markers that carry a value.
    /// </summary>
    public static async Task<bool> IsExcludedFromHistoryAsync(IReadOnlyCollection<string> formatNames, Func<string, Task<byte[]?>> readValue)
    {
        ArgumentNullException.ThrowIfNull(formatNames);
        ArgumentNullException.ThrowIfNull(readValue);
        if (formatNames.Any(ExclusionMarkers.Contains))
        {
            return true;
        }

        var canInclude = formatNames.FirstOrDefault(name => string.Equals(name, WindowsCanIncludeInHistoryFormat, StringComparison.OrdinalIgnoreCase));
        if (canInclude is not null && await readValue(canInclude).ConfigureAwait(false) is { Length: >= 4 } flag && BitConverter.ToInt32(flag, 0) == 0)
        {
            return true;
        }

        var kdeHint = formatNames.FirstOrDefault(name => string.Equals(name, KdePasswordManagerHintFormat, StringComparison.Ordinal));
        if (kdeHint is not null && await readValue(kdeHint).ConfigureAwait(false) is { } hint
            && System.Text.Encoding.UTF8.GetString(hint).Trim('\0', ' ', '\n') == "secret")
        {
            return true;
        }

        return false;
    }

    /// <summary>Upper bound for a single raw format. Larger blobs are skipped so history stays responsive.</summary>
    public const int MaxRawFormatBytes = 32 * 1024 * 1024;

    public static bool IsPlainText(string formatName) => PlainTextFormats.Contains(Normalize(formatName));

    public static bool IsRichText(string formatName) => RichTextFormats.Contains(Normalize(formatName));

    public static bool IsHtml(string formatName)
    {
        var name = Normalize(formatName);
        return name.Contains("html", StringComparison.OrdinalIgnoreCase);
    }

    public static bool IsFileList(string formatName) => FileListFormats.Contains(Normalize(formatName));

    public static bool IsImage(string formatName)
    {
        var name = Normalize(formatName);
        return ImageFormats.Contains(name) || name.StartsWith("image/", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>Whether a raw format should be read from the clipboard at all.</summary>
    public static bool ShouldCapture(string formatName, long size = 0)
    {
        if (string.IsNullOrWhiteSpace(formatName) || size > MaxRawFormatBytes)
        {
            return false;
        }

        var name = Normalize(formatName);
        return !IgnoredFormats.Contains(name) && !ExclusionMarkers.Contains(name);
    }

    /// <summary>
    /// Whether a raw format should be written back when restoring <paramref name="snapshot"/>.
    /// Formats that the portable parts already produce (plain text, the image, the file list) are skipped,
    /// because writing both would give the clipboard two competing values for the same native format.
    /// </summary>
    public static bool ShouldRestore(string formatName, ClipboardSnapshot snapshot)
    {
        ArgumentNullException.ThrowIfNull(snapshot);
        if (!ShouldCapture(formatName))
        {
            return false;
        }

        if (snapshot.Text is not null && IsPlainText(formatName))
        {
            return false;
        }

        if (snapshot.Image is not null && IsImage(formatName))
        {
            return false;
        }

        if (snapshot.Files.Count > 0 && IsFileList(formatName))
        {
            return false;
        }

        return true;
    }

    /// <summary>Returns the first rich (HTML or RTF) raw format, if any.</summary>
    public static RawClipboardFormat? FindRichText(ClipboardSnapshot snapshot)
    {
        ArgumentNullException.ThrowIfNull(snapshot);
        return snapshot.RawFormats.FirstOrDefault(f => IsRichText(f.Name));
    }

    private static string Normalize(string formatName) => formatName.Trim();
}
